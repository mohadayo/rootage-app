git push
```
> force pushは絶対にしない！チームに迷惑がかかります。

### 3. ブランチを間違えて作業した
```bash
# 変更を一時退避
git stash
# 正しいブランチに切り替え
git checkout correct-branch
# 退避した変更を適用
git stash pop
```

### 4. コンフリクトが起きた
1. `<<<<<<<` と `>>>>>>>` の間を確認
2. どちらの変更を残すか判断
3. マーカーを削除して正しいコードにする
4. `git add` → `git commit`

### 困ったら
- まず `git status` で状況確認
- 不安なら先輩に相談してから操作する', 2),

